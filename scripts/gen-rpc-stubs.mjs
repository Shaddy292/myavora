// Generates src/rpc/*.js — client-side stand-ins for the server-function
// modules in src/lib/*-fns.js. Used only by the PHP/cPanel build target
// (AVORA_TARGET=php): each export posts { data } to /api/fn/<module>/<name>
// and returns the PHP handler's `result` field.
//
// Run: node scripts/gen-rpc-stubs.mjs
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const LIB = path.join("src", "lib");
const OUT = path.join("src", "rpc");

// Exports that are plain values/helpers rather than server functions. Copied
// verbatim because a stub that imported the original would drag server-only
// modules into the browser bundle.
const PURE_EXTRAS = {
  "finance-fns.js": [
    "export const FEE_FALLBACKS = { vendorPct: 10, riderPct: 10, joinFee: 30000, monthlyFee: 2000 };",
    "export const periodOf = (date = new Date()) => new Date(date).toISOString().slice(0, 7);",
  ].join("\n\n"),
};

const SERVER_ONLY = new Set(["loadFees", "ensureVendorCharges"]);

mkdirSync(OUT, { recursive: true });

const files = readdirSync(LIB).filter((file) => file.endsWith("-fns.js")).sort();
const summary = [];

for (const file of files) {
  const source = readFileSync(path.join(LIB, file), "utf8");
  const moduleName = file.replace(/-fns\.js$/, "");
  const names = [...source.matchAll(/export const ([A-Za-z0-9_]+)\s*=\s*createServerFn/g)].map((m) => m[1]);
  const everyExport = [...source.matchAll(/export (?:async )?(?:const|function) ([A-Za-z0-9_]+)/g)].map((m) => m[1]);
  const unexplained = everyExport.filter((name) => !names.includes(name) && !SERVER_ONLY.has(name));
  if (unexplained.length && !PURE_EXTRAS[file]) {
    throw new Error(`${file}: add stub definitions for non-server exports: ${unexplained.join(", ")}`);
  }

  const lines = [
    `// Generated by scripts/gen-rpc-stubs.mjs from src/lib/${file}. Do not edit by hand.`,
    `import { callFn } from "./_call.js";`,
    "",
    ...names.map(
      (name) => `export const ${name} = (options) => callFn(${JSON.stringify(moduleName)}, ${JSON.stringify(name)}, options?.data);`
    ),
  ];
  if (PURE_EXTRAS[file]) lines.push("", PURE_EXTRAS[file]);

  writeFileSync(path.join(OUT, file), `${lines.join("\n")}\n`);
  summary.push(`${file.padEnd(26)} ${names.length} fn(s)`);
}

// Local guard so regeneration never silently drops exports.
for (const file of files) {
  const source = readFileSync(path.join(LIB, file), "utf8");
  const original = [...source.matchAll(/export const ([A-Za-z0-9_]+)\s*=\s*createServerFn/g)].map((m) => m[1]);
  const stub = readFileSync(path.join(OUT, file), "utf8");
  const emitted = [...stub.matchAll(/export const ([A-Za-z0-9_]+)/g)].map((m) => m[1]);
  const missing = original.filter((name) => !emitted.includes(name));
  if (missing.length) throw new Error(`${file}: stub is missing ${missing.join(", ")}`);
}

console.log(summary.join("\n"));
